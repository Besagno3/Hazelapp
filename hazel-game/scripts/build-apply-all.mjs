#!/usr/bin/env node
// Builds supabase/apply_all_migrations.sql: every file in supabase/migrations/,
// in order, inside one transaction, each recorded in Supabase's own migration
// history table (supabase_migrations.schema_migrations — the one the Supabase
// CLI's `db push` reads). Every migration is written to be re-runnable, so the
// script is safe on a fresh project, a partly migrated one, or a complete one.
//
//   node scripts/build-apply-all.mjs          # regenerate the file
//   node scripts/build-apply-all.mjs --check  # CI: fail if it's out of date
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase');
const outPath = join(root, 'apply_all_migrations.sql');
const files = readdirSync(join(root, 'migrations'))
  .filter((f) => /^\d+_.+\.sql$/.test(f))
  .sort();

const sqlString = (s) => `'${s.replaceAll("'", "''")}'`;

const parts = [
  `-- Hazel Quest — apply AND record every migration (0001 → ${files.at(-1).split('_')[0]}).
-- GENERATED by scripts/build-apply-all.mjs from supabase/migrations/ — do not
-- edit by hand; edit a migration and re-run the script.
--
-- Paste the whole file into the Supabase SQL Editor and click Run.
--   * Safe to run on a fresh project, a partly migrated one, or a finished one:
--     every statement is idempotent (IF NOT EXISTS / OR REPLACE /
--     DROP POLICY IF EXISTS + CREATE), so re-running never fails and it also
--     repairs a missing or wrong policy/grant/column.
--   * All-or-nothing: it runs in one transaction; any error rolls it all back.
--   * Each migration is recorded in supabase_migrations.schema_migrations, so
--     \`supabase db push\` afterwards sees them as applied.
--   * Afterwards, the SELECT at the bottom lists what is recorded.

begin;

-- The history table the Supabase CLI uses (created here if this project has
-- never run \`supabase db push\`).
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (
  version    text primary key,
  statements text[],
  name       text
);
`,
];

for (const file of files) {
  const [version, ...rest] = file.replace(/\.sql$/, '').split('_');
  const name = rest.join('_');
  const body = readFileSync(join(root, 'migrations', file), 'utf8').trim();
  parts.push(`
-- ============================================================================
-- ${file}
-- ============================================================================
${body}

insert into supabase_migrations.schema_migrations (version, name, statements)
values (${sqlString(version)}, ${sqlString(name)}, array[]::text[])
on conflict (version) do nothing;
`);
}

parts.push(`
commit;

-- What's recorded now:
select version, name from supabase_migrations.schema_migrations order by version;
`);

const out = parts.join('');

if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(outPath, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== out) {
    console.error('supabase/apply_all_migrations.sql is out of date — run: node scripts/build-apply-all.mjs');
    process.exit(1);
  }
  console.log(`apply_all_migrations.sql is up to date (${files.length} migrations).`);
} else {
  writeFileSync(outPath, out);
  console.log(`Wrote ${outPath} (${files.length} migrations).`);
}
